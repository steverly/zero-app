export function t(language, path) {
  const root = ZERO_I18N[language] || ZERO_I18N.fr;

  return String(path || "")
    .split(".")
    .reduce(
      (value, key) =>
        value && value[key] !== undefined
          ? value[key]
          : undefined,
      root
    );
}

export function getZeroCopy(language) {
  return ZERO_I18N[language] || ZERO_I18N.fr;
}
